def normalize_language(value: str) -> str:
    language = str(value or "").strip().lower()
    return language if language in LANGUAGES else DEFAULT_LANGUAGE


def tr(language: str, key: str, **kwargs: object) -> str:
    text = _TEXTS[normalize_language(language)][key]
    return text.format(**kwargs) if kwargs else text


def default_notify_templates(language: str) -> tuple[str, str]:
    return tr(language, "notify_title_default"), tr(language, "notify_msg_default")


def default_sleep_templates(language: str) -> tuple[str, str]:
    return tr(language, "sleep_title_default"), tr(language, "sleep_msg_default")
